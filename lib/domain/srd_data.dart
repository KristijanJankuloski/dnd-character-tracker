  id: 'srd-${name.toLowerCase().replaceAll(' ', '-')}',
  name: name,
  type: type,
  weight: weight,
  valueGp: gp,
  quantity: qty,
  healAmount: heal,
  description: desc,
  source: 'SRD',
);

