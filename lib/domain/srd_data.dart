Item _weapon(
  String name,
  String dice,
  String type, {
  double weight = 1,
  double gp = 0,
  bool ranged = false,
  bool finesse = false,
  bool twoHanded = false,
  bool light = false,
  bool reach = false,
  String? versatile,
  String range = '',
  bool martial = false,
}) => Item(
  id: 'srd-${name.toLowerCase().replaceAll(' ', '-')}',
  name: name,
  type: ItemType.weapon,
  weight: weight,
  valueGp: gp,
  source: 'SRD',
  weapon: WeaponStats(
    damageDice: dice,
    damageType: type,
    ranged: ranged,
    finesse: finesse,
    twoHanded: twoHanded,
    light: light,
    reach: reach,
    versatileDice: versatile,
    range: range,
    martial: martial,
  ),
);

Item _armor(
  String name,
  ArmorCategory cat,
  int ac,
  double weight,
  double gp, {
  int str = 0,
  bool stealth = false,
}) => Item(
  id: 'srd-${name.toLowerCase().replaceAll(' ', '-')}',
  name: name,
  type: ItemType.armor,
  weight: weight,
  valueGp: gp,
  source: 'SRD',
  armor: ArmorStats(
    category: cat,
    baseAc: ac,
    strReq: str,
    stealthDisadv: stealth,
  ),
);

Item _gear(
  String name,
